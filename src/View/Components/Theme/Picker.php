<?php

namespace Fsteltenkamp\TwcssComponents\View\Components\Theme;

use Closure;
use Fsteltenkamp\TwcssComponents\View\Component;
use Illuminate\Contracts\View\View;
use Illuminate\Support\Str;

/**
 * Lets the visitor choose the skin (the look: data-skin on <html>), the theme (the
 * colour scheme: data-theme on <html>; `custom` adds one Tailwind palette per role as
 * data-theme-<role>) and the light/dark/system mode (x-fltc::darkmode.toggle, which
 * owns that storage and the OS-following system mode). Each choice is stored under its
 * own key. Pair it with x-fltc::theme.script in <head> so the choices apply before the
 * first paint.
 */
class Picker extends Component
{
    public const ROLES = ['primary', 'secondary', 'accent', 'base', 'info', 'success', 'warning', 'danger'];

    /**
     * The default theme's palette per role (resources/css/themes.css, generated by
     * tools/themes.py): what a custom theme starts from.
     */
    public const DEFAULT_ROLES = [
        'primary' => 'blue', 'secondary' => 'violet', 'accent' => 'teal', 'base' => 'slate',
        'info' => 'sky', 'success' => 'green', 'warning' => 'amber', 'danger' => 'red',
    ];

    public const PALETTES = [
        'slate', 'gray', 'zinc', 'neutral', 'stone', 'taupe', 'mauve', 'mist', 'olive',
        'red', 'orange', 'amber', 'yellow', 'lime', 'green', 'emerald', 'teal', 'cyan',
        'sky', 'blue', 'indigo', 'violet', 'purple', 'fuchsia', 'pink', 'rose',
    ];

    /** @var array<string, string> skin name => label */
    public array $skinOptions;

    /** @var array<string, string> theme name => label */
    public array $themeOptions;

    /** @var array<string, string> palette name => label, for the custom theme's roles */
    public array $paletteOptions;

    public bool $hasCustom;

    public string $classList;

    /**
     * @param  array<int|string, string>  $skins  skin names, or name => label; empty hides the select
     * @param  array<int|string, string>  $themes  theme names, or name => label; empty hides the select.
     *                                             Include `custom` to let visitors pick a palette per role
     * @param  array<int|string, string>  $palettes  palettes offered per role in the custom theme
     */
    public function __construct(
        public array $skins = ['default', 'cyberpunk', 'fantasy', 'wh40k'],
        public array $themes = ['default', 'cyberpunk', 'fantasy', 'wh40k', 'dracula', 'nord', 'catppuccin', 'solarized', 'gruvbox', 'custom'],
        public array $palettes = self::PALETTES,
        public string $skinStorageKey = 'fltc-skin',
        public string $themeStorageKey = 'fltc-theme',
        public ?string $defaultSkin = null,
        public ?string $defaultTheme = null,
        public string $color = 'base',
        public bool $mode = true,
        public bool $stacked = false,
        public string $skinLabel = '',
        public string $themeLabel = '',
        public string $modeLabel = '',
    ) {
        $this->skinOptions = self::options($skins);
        $this->themeOptions = self::options($themes);
        $this->paletteOptions = self::options($palettes);
        $this->hasCustom = array_key_exists('custom', $this->themeOptions);

        $this->defaultSkin = $defaultSkin ?? array_key_first($this->skinOptions) ?? 'default';
        $this->defaultTheme = $defaultTheme ?? array_key_first($this->themeOptions) ?? 'default';
        $this->skinLabel = $skinLabel !== '' ? $skinLabel : __('Skin');
        $this->themeLabel = $themeLabel !== '' ? $themeLabel : __('Theme');
        $this->modeLabel = $modeLabel !== '' ? $modeLabel : __('Mode');
        $this->classList = $stacked ? 'flex flex-col gap-4' : 'flex flex-wrap items-end gap-4';
    }

    /**
     * @param  array<int|string, string>  $names
     * @return array<string, string>
     */
    private static function options(array $names): array
    {
        return collect($names)
            ->mapWithKeys(fn (string $label, int|string $name) => is_int($name)
                ? [$label => Str::headline($label)]
                : [$name => $label])
            ->all();
    }

    public function render(): View|Closure|string
    {
        return view('fltc::components.theme.picker');
    }
}
